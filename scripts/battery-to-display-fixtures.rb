#!/usr/bin/env ruby
# frozen_string_literal: true

# Oracle measurements of `Formula#to_display(type)` for
# `test/compat/to-display.spec.ts`: each input is parsed once, then
# `to_display` is called with the type as a Symbol (the dispatch Opal's
# lowercase JS string reaches), as a native Ruby String (lowercase and
# uppercase), and with names outside `MATH_ZONE_TYPES`. The native-String
# rows are native-MRI results, recorded as such; they are not a measurement
# of the Opal wrapper.
#
#   cd ../plurimath-oracle && mise x ruby@4.0.1 -- bundle exec ruby \
#     <worktree>/scripts/battery-to-display-fixtures.rb \
#     --oracle . --out <worktree>/test/compat
#
# Parse sits outside the rescue: only `to_display` outcomes are recorded.
# Named without the `generate-` prefix for the reason
# `battery-unicodemath-fixtures.rb` gives.

require "digest"
require "fileutils"
require "json"
require "optparse"

GENERATOR_RELATIVE_PATH = "scripts/battery-to-display-fixtures.rb"

INPUTS = ["frac(1)(2)", "alpha", "x^2", "sqrt(2)", "vec(v)", "x+y=2"].freeze
LANGS = %w[asciimath latex mathml omml unicodemath].freeze
INVALID_LANGS = %w[html unicode].freeze

options = { oracle: nil, out: "test/compat" }
OptionParser.new do |o|
  o.on("--oracle PATH", "clean pinned plurimath checkout") { |v| options[:oracle] = v }
  o.on("--out PATH", "output directory (default test/compat)") { |v| options[:out] = v }
end.parse!

abort "--oracle is required" unless options[:oracle]

oracle = File.expand_path(options[:oracle])
lib = File.join(oracle, "lib")
unless File.directory?(lib) && File.exist?(File.join(lib, "plurimath.rb"))
  abort "not a plurimath checkout: #{lib}"
end

$LOAD_PATH.unshift(lib)
require "plurimath"
require "plurimath/version"

unless Gem.loaded_specs.key?("plurimath")
  abort "REFUSING: the plurimath gem is not activated. Re-run with " \
        "BUNDLE_GEMFILE=#{oracle}/Gemfile mise x -- bundle exec ruby #{__FILE__} ..."
end

loaded = $LOADED_FEATURES.grep(%r{/plurimath\.rb\z}).first
unless loaded&.start_with?(lib)
  abort "REFUSING: loaded #{loaded.inspect}, not the pinned checkout at #{lib}. " \
        "An installed gem answers from a different version."
end

def outcome
  { "result" => yield }
rescue StandardError => e
  { "raises" => e.class.name }
end

rows = INPUTS.map do |input|
  formula = Plurimath::Math.parse(input, :asciimath)
  {
    "input" => input,
    "symbol" => LANGS.to_h { |l| [l, outcome { formula.to_display(l.to_sym) }] },
    "nativeString" => LANGS.to_h { |l| [l, outcome { formula.to_display(l.dup) }] },
    "nativeUpcaseString" => LANGS.to_h { |l| [l, outcome { formula.to_display(l.upcase) }] },
    "invalid" => INVALID_LANGS.to_h { |l| [l, outcome { formula.to_display(l.dup) }] },
  }
end

oracle_git_status = `git -C #{oracle} status --porcelain`
oracle_clean = oracle_git_status.strip.empty?
abort "REFUSING: oracle checkout at #{oracle} is dirty:\n#{oracle_git_status}" unless oracle_clean

payload = {
  "$comment" => "GENERATED by #{GENERATOR_RELATIVE_PATH}. Do not edit.",
  "schema" => "plurimath-compat/to-display/1",
  "oracleCommit" => `git -C #{oracle} rev-parse HEAD`.strip,
  "oracleClean" => oracle_clean,
  "generatorSha256" => Digest::SHA256.file(__FILE__).hexdigest,
  "casesSha256" => Digest::SHA256.hexdigest(JSON.generate(rows)),
  "cases" => rows,
}

dir = File.expand_path(options[:out])
FileUtils.mkdir_p(dir)
out = File.join(dir, "to-display-fixtures.json")
File.binwrite(out, "#{JSON.pretty_generate(payload)}\n")
puts "to_display fixtures: #{rows.length} inputs -> #{out}"
