# frozen_string_literal: true

# Generate HTML Text's own unicode[:name] lookup from the loaded Ruby oracle.
# Run with the oracle bundle: ruby -I<oracle>/lib scripts/generate-html-text-data.rb
# --source-checkout PATH verifies the two oracle source inputs against a clean
# Git checkout. A copied runtime snapshot is permitted only when those bytes match.
# --out PATH overrides src/formats/html/generated-text. No unrelated tables change.
require 'plurimath'
require 'json'
require 'digest'
require 'open3'
require 'fileutils'
require 'optparse'

options = {}
OptionParser.new do |p|
  p.on('--source-checkout PATH') { |v| options[:source] = File.expand_path(v) }
  p.on('--out PATH') { |v| options[:out] = File.expand_path(v) }
end.parse!
raise '--source-checkout is required' unless options[:source]
source = options.fetch(:source)
def git(path, *args)
  out, err, result = Open3.capture3('git', '-C', path, *args)
  raise "git #{args.inspect}: #{err}" unless result.success?
  out
end
raise 'source checkout must be clean' unless git(source, 'status', '--porcelain').empty?
commit = git(source, 'rev-parse', 'HEAD').strip
oracle = File.expand_path(Gem.loaded_specs.fetch('plurimath').full_gem_path)
inputs = %w[lib/plurimath/math/function/text.rb lib/plurimath/mathml/constants.rb]
source_hashes = inputs.to_h do |path|
  bytes = File.binread(File.join(oracle, path))
  raise "snapshot does not match source HEAD: #{path}" unless bytes == git(source, 'show', "#{commit}:#{path}").b
  [path, Digest::SHA256.hexdigest(bytes)]
end
constants = Plurimath::Mathml::Constants
unicode = constants::UNICODE_SYMBOLS.invert
fallback = constants::SYMBOLS.invert
# Ruby's invert keeps the last duplicate value; the first hash wins across maps.
lookup = fallback.merge(unicode).select { |name, _| name.is_a?(String) && /\A\w+\z/.match?(name) }.sort.to_h
text = Plurimath::Math::Function::Text
lookup = lookup.to_h do |name, value|
  actual = text.new("unicode[:#{name}]").to_html
  raise "Text#to_html lookup differs: #{name}" unless actual == value.to_s
  [name, actual]
end
probe_inputs = ['unicode[:nosuchname]', 'unicode[:_missing_]', 'unicode[:alpha]unicode[:beta]',
  'before unicode[:alpha] middle unicode[:nosuchname] after unicode[:Gamma]',
  'unicode[:a-b] unicode[:] unicode[:α] UNICODE[:alpha]', 'unicode[:alpha]unicode[:alpha]', 'plain & < > text']
probes = probe_inputs.map { |input| [input, text.new(input).to_html] }
raise 'unknown token is not deleted' unless probes[0][1] == '' && probes[1][1] == ''
root = File.expand_path('..', __dir__)
out = options[:out] || File.join(root, 'src/formats/html/generated-text')
FileUtils.mkdir_p(out)
quote = ->(v) { JSON.generate(v, ascii_only: true) }
header = "/** GENERATED by scripts/generate-html-text-data.rb; regenerate, do not edit. */\n"
table = lookup.map { |k,v| "  [#{quote.call(k)}, #{quote.call(v)}]," }.join("\n")
File.write(File.join(out, 'symbols.ts'), header + <<~TS)

  /** Word-shaped Text tokens only; measured through Ruby Text#to_html. */
  export const HTML_TEXT_SYMBOLS: ReadonlyMap<string, string> = new Map([
  #{table}
  ]);

  export const HTML_TEXT_PROBES: readonly (readonly [string, string])[] = [
  #{probes.map { |k,v| "  [#{quote.call(k)}, #{quote.call(v)}]," }.join("\n")}
  ];
TS
provenance = { generator: 'scripts/generate-html-text-data.rb', generatorSha256: Digest::SHA256.file(__FILE__).hexdigest,
  oracleCommit: commit, oracleVersion: Gem.loaded_specs.fetch('plurimath').version.to_s, oracleSourceSha256: source_hashes,
  bundleLockSha256: Digest::SHA256.file(ENV.fetch('BUNDLE_GEMFILE', File.join(oracle, 'Gemfile')) + '.lock').hexdigest,
  formatterVersion: JSON.parse(File.read(File.join(root, 'node_modules/@biomejs/biome/package.json'))).fetch('version'),
  formatterConfigSha256: Digest::SHA256.file(File.join(root,'biome.json')).hexdigest,
  rubyVersion: RUBY_VERSION, verifiedNames: lookup.length, verifiedEdgeProbes: probes.length }
File.write(File.join(out,'provenance.json'), JSON.pretty_generate(provenance)+"\n")
formatter_out, formatter_err, formatter_status = Open3.capture3(File.join(root,'node_modules/.bin/biome'), 'format', '--write', File.join(out,'symbols.ts'), File.join(out,'provenance.json'))
raise "formatter failed: #{formatter_out}#{formatter_err}" unless formatter_status.success?
puts "#{lookup.length} reachable names and #{probes.length} edge probes verified via Text#to_html"
