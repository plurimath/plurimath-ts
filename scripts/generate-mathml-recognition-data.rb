# frozen_string_literal: true

# Run in the locked oracle bundle with -I<oracle>/lib. --source-checkout must
# point to a clean reference checkout; copied runtime source bytes are verified.
# Owns only MathML's generated-recognition directory; no translation tables change.
require "plurimath"
require "mml"
require "json"
require "digest"
require "open3"
require "fileutils"
require "optparse"

options = {}
OptionParser.new do |parser|
  parser.on("--source-checkout PATH") { |path| options[:source] = File.expand_path(path) }
  parser.on("--out PATH") { |path| options[:out] = File.expand_path(path) }
end.parse!
source = options.fetch(:source) { raise "--source-checkout is required" }
def git(path, *args)
  output, error, status = Open3.capture3("git", "-C", path, *args)
  raise "git #{args.inspect}: #{error}" unless status.success?

  output
end
raise "reference checkout must be clean" unless git(source, "status", "--porcelain").empty?

commit = git(source, "rev-parse", "HEAD").strip
oracle = Gem.loaded_specs.fetch("plurimath").full_gem_path
oracle_inputs = %w[
  lib/plurimath/math.rb
  lib/plurimath/mathml/parser.rb
  lib/plurimath/mathml/translator.rb
  lib/plurimath/mathml/formula_transformation.rb
]
oracle_hashes = oracle_inputs.to_h do |path|
  bytes = File.binread(File.join(oracle, path))
  raise "runtime snapshot differs from reference HEAD: #{path}" unless bytes == git(source, "show", "#{commit}:#{path}").b

  [path, Digest::SHA256.hexdigest(bytes)]
end
context = Mml::V4::Configuration.context
rows = Mml::V4::Math.mappings_for(:xml).elements.map do |mapping|
  klass = Mml::V4::Math.attributes.fetch(mapping.to).type(context)
  raise "unexpected mapped class for #{mapping.name}: #{klass}" unless klass.name.start_with?("Mml::V4::")

  [mapping.name, klass.name.delete_prefix("Mml::V4::")]
end.sort
raise "empty or duplicate MathML mapping" if rows.empty? || rows.map(&:first).uniq.length != rows.length

# Outcomes are measured from the public Ruby parser. These probes prevent eager
# recognition errors from rejecting children ignored by the translator.
probes = {
  "recognized pi" => "<pi/>",
  "recognized apply" => "<apply><plus/><ci>x</ci><cn>1</cn></apply>",
  "recognized inside mrow" => "<mrow><pi/></mrow>",
  "recognized between supported siblings" => "<mi>a</mi><pi/><mi>b</mi>",
  "unknown subtree" => "<foo><mi>x</mi></foo>",
  "unknown with supported sibling" => "<foo><mi>z</mi></foo><mi>x</mi>",
  "recognized inside unknown subtree" => "<foo><pi/></foo><mi>x</mi>",
  "recognized inside token" => "<mi>a<pi/>b</mi>",
  "recognized inside mspace" => "<mspace><pi/></mspace>",
  "recognized inside annotation" => "<annotation><pi/></annotation><mi>x</mi>",
  "recognized inside annotation-xml" => "<annotation-xml><ci>x</ci></annotation-xml><mi>x</mi>",
  "recognized inside semantics annotation-xml" => "<semantics><mi>x</mi><annotation-xml><ci>x</ci></annotation-xml></semantics>",
}.map do |name, body|
  input = %(<math xmlns="http://www.w3.org/1998/Math/MathML">#{body}</math>)
  result = begin
    { parsed: true, asciimath: Plurimath::Math.parse(input, :mathml).to_asciimath }
  rescue Plurimath::Math::ParseError => error
    { parsed: false, error: error.class.name }
  end
  { name: name, input: input }.merge(result)
end
mml = Gem.loaded_specs.fetch("mml")
mml_root = File.expand_path(mml.full_gem_path)
mml_hashes = $LOADED_FEATURES.select { |path| path.start_with?("#{mml_root}/lib/") }.sort.to_h do |path|
  [path.delete_prefix("#{mml_root}/"), Digest::SHA256.file(path).hexdigest]
end
raise "mapping source files absent" unless %w[lib/mml/common_elements.rb lib/mml/v4/common_elements.rb lib/mml/v4/math.rb].all? { |path| mml_hashes.key?(path) }

root = File.expand_path("..", __dir__)
out = options[:out] || File.join(root, "src/formats/mathml/generated-recognition")
FileUtils.mkdir_p(out)
quote = ->(value) { JSON.generate(value) }
File.write(File.join(out, "elements.ts"), <<~TS)
  /** GENERATED by scripts/generate-mathml-recognition-data.rb; see provenance.json.
   * Ruby Mml::V4::Math XML names and their resolved attribute model class kinds.
   * Recognition is separate from translation; the existing supported kinds win.
   */
  export const MATHML_RECOGNIZED_ELEMENT_COUNT: number = #{rows.length};
  export const MATHML_RECOGNIZED_ELEMENTS: ReadonlyMap<string, string> = new Map([
  #{rows.map { |name, kind| "  [#{quote.call(name)}, #{quote.call(kind)}]," }.join("\n")}
  ]);
TS
File.write(File.join(out, "context-probes.json"), JSON.pretty_generate(probes) + "\n")
provenance = {
  generator: "scripts/generate-mathml-recognition-data.rb",
  generatorSha256: Digest::SHA256.file(__FILE__).hexdigest,
  oracleCommit: commit, oracleVersion: Gem.loaded_specs.fetch("plurimath").version.to_s,
  oracleSourceSha256: oracle_hashes, mmlVersion: mml.version.to_s,
  mmlSourceSha256: mml_hashes,
  lutamlModelVersion: Gem.loaded_specs.fetch("lutaml-model").version.to_s,
  bundleLockSha256: Digest::SHA256.file(ENV.fetch("BUNDLE_GEMFILE", File.join(oracle, "Gemfile")) + ".lock").hexdigest,
  rubyVersion: RUBY_VERSION, verifiedMappings: rows.length, verifiedContextProbes: probes.length,
  formatterVersion: JSON.parse(File.read(File.join(root, "node_modules/@biomejs/biome/package.json"))).fetch("version"),
  formatterConfigSha256: Digest::SHA256.file(File.join(root, "biome.json")).hexdigest,
}
File.write(File.join(out, "provenance.json"), JSON.pretty_generate(provenance) + "\n")
paths = %w[elements.ts context-probes.json provenance.json].map { |path| File.join(out, path) }
stdout, stderr, status = Open3.capture3(File.join(root, "node_modules/.bin/biome"), "format", "--write", *paths)
raise "formatter failed: #{stdout}#{stderr}" unless status.success?

puts "#{rows.length} runtime mappings and #{probes.length} public-parser context probes measured"
