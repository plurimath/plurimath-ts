#!/usr/bin/env ruby
# frozen_string_literal: true

# Regenerate the three legacy AsciiMath-input render sweeps from their ordered
# input seed. Run with the pinned oracle's published, frozen bundle:
#
#   BUNDLE_GEMFILE=/path/to/plurimath/Gemfile BUNDLE_FROZEN=true \
#     bundle exec ruby scripts/generate-render-sweeps.rb --oracle /path/to/plurimath

require "digest"
require "fileutils"
require "json"
require "optparse"

ROOT = File.expand_path("..", __dir__)
SEED_RELATIVE_PATH = "scripts/seeds/render-sweep-inputs.json"
GENERATOR_RELATIVE_PATH = "scripts/generate-render-sweeps.rb"
FORMATS = %w[asciimath latex mathml].freeze
DESCRIPTIONS = {
  "asciimath" => "Gem-verified AsciiMath render sweep: input -> Plurimath::Math.parse(input, :asciimath).to_asciimath, or the refusal.",
  "latex" => "Gem-verified LaTeX render sweep: input -> Plurimath::Math.parse(input, :asciimath).to_latex, or the refusal.",
  "mathml" => "Gem-verified MathML render sweep: the established 1,642-input list re-rendered through Plurimath::Math.parse(input, :asciimath).to_mathml (default options) on the pinned oracle. Generated by scripts/generate-render-sweeps.rb.",
}.freeze

options = { oracle: nil, out: "test/formats" }
OptionParser.new do |parser|
  parser.on("--oracle PATH", "clean pinned plurimath checkout") { |path| options[:oracle] = path }
  parser.on("--out PATH", "output root (default test/formats)") { |path| options[:out] = path }
end.parse!
abort "--oracle is required" unless options[:oracle]

oracle = File.realpath(options[:oracle])
lib = File.join(oracle, "lib")
abort "not a plurimath checkout: #{lib}" unless File.file?(File.join(lib, "plurimath.rb"))
expected_gemfile = File.join(oracle, "Gemfile")
abort "BUNDLE_GEMFILE must select #{expected_gemfile}" unless
  ENV["BUNDLE_GEMFILE"] && File.realpath(ENV["BUNDLE_GEMFILE"]) == File.realpath(expected_gemfile)
abort "BUNDLE_FROZEN=true is required" unless ENV["BUNDLE_FROZEN"] == "true"

$LOAD_PATH.unshift(lib)
require "plurimath"
require "plurimath/version"
require_relative "generate-corpus"

gem_spec = Gem.loaded_specs["plurimath"]
abort "the oracle gem must be activated by bundle exec" unless gem_spec
loaded = $LOADED_FEATURES.grep(%r{/plurimath\.rb\z}).first
abort "loaded #{loaded.inspect}, expected #{lib}/plurimath.rb" unless loaded == File.join(lib, "plurimath.rb")

CorpusGenerator.require_ox_engine!
lockfile = CorpusGenerator.lockfile_path(oracle)
dependencies = CorpusGenerator.dependency_provenance(oracle, gem_spec)
unless dependencies[:external_path_sources].empty?
  abort "path-pinned dependencies are not published: #{dependencies[:external_path_sources].join(', ')}"
end

out = File.expand_path(options[:out], ROOT)
paths = FORMATS.to_h { |format| [format, File.join(out, format, "render-sweep.json")] }
CorpusGenerator.check_checkouts!(oracle, oracle, paths.values, false)

seed_path = File.join(ROOT, SEED_RELATIVE_PATH)
inputs = JSON.parse(File.read(seed_path))
abort "seed must be a nonempty array of unique strings" unless
  inputs.is_a?(Array) && !inputs.empty? && inputs.all? { |input| input.is_a?(String) } &&
    inputs.uniq.length == inputs.length
abort "expected 1,642 legacy inputs, got #{inputs.length}" unless inputs.length == 1642

sha = lambda { |path| Digest::SHA256.file(path).hexdigest }
provenance = {
  "seed" => { "path" => SEED_RELATIVE_PATH, "sha256" => sha.call(seed_path) },
  "generator" => { "path" => GENERATOR_RELATIVE_PATH,
                   "sha256" => sha.call(File.join(ROOT, GENERATOR_RELATIVE_PATH)) },
  "lockfile" => { "path" => "Gemfile.lock", "sha256" => sha.call(lockfile) },
}
oracle_record = {
  "gem" => "plurimath",
  "version" => Plurimath::VERSION,
  "commit" => CorpusGenerator.checkout_provenance(oracle, []).fetch("commit"),
}

cases = FORMATS.to_h { |format| [format, []] }
inputs.each do |input|
  begin
    formula = Plurimath::Math.parse(input, :asciimath)
  rescue Plurimath::Math::ParseError => error
    FORMATS.each do |format|
      cases.fetch(format) << { "input" => input, "error" => "parse", "errorClass" => error.class.name }
    end
    next
  end

  FORMATS.each do |format|
    row = { "input" => input }
    begin
      row["render"] = formula.public_send("to_#{format}")
    rescue Plurimath::Math::ParseError => error
      row["error"] = "render"
      row["errorClass"] = error.class.name
    end
    cases.fetch(format) << row
  end
end

FORMATS.each do |format|
  payload = {
    "description" => DESCRIPTIONS.fetch(format),
    "oracle" => oracle_record,
    "count" => inputs.length,
    "cases" => cases.fetch(format),
    "inputs" => provenance,
  }
  path = paths.fetch(format)
  FileUtils.mkdir_p(File.dirname(path))
  File.write(path, JSON.pretty_generate(payload) + "\n")
  puts "wrote #{path}: #{inputs.length} cases"
end
