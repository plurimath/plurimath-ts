#!/usr/bin/env node
/** biome-ignore-all lint/style/useNamingConvention: manifest keys are the snake_case pin schema shared with assets/wasm/manifest.json. */
/**
 * Pin a built facade WASM packet: the single step that turns the facade from
 * `pending` into a shipped asset.
 *
 *   node scripts/pin-facade-wasm.mjs <packet-dir>
 *
 * The packet directory is the output of the plurimath-rs facade WASM build:
 * `bindgen-result.json`, `build-result.json` and `web/` with the official
 * wasm-bindgen `--target web` output (`facade_bg.wasm`, `facade.js`,
 * `facade.d.ts`). The script checks every packet file against the digests the
 * packet records, checks the source revision against
 * `assets/facade/manifest.json`, checks that the module's host imports are
 * exactly the ones `src/facade/wasm.ts` admits and that it exports the ABI-v1
 * facade functions, then writes:
 *
 *   assets/facade/plurimath_facade.wasm      the binary (byte-exact)
 *   src/facade/facade-wasm/facade.{js,d.ts}  the official glue (byte-exact)
 *   assets/facade/manifest.json              status "pinned", digests, build
 *   src/facade/asset.ts                      FACADE_WASM_ASSET, generated
 *   package.json                             the `./facade/plurimath_facade.wasm` export
 *
 * Notices, dependency notices and Cargo.lock are source-determined and already
 * pinned in the manifest; the gate re-checks them after the build.
 */
import { createHash } from "node:crypto";
import { copyFileSync, existsSync, readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packet = process.argv[2] ? resolve(process.argv[2]) : undefined;
if (!packet) {
  console.error("usage: node scripts/pin-facade-wasm.mjs <packet-dir>");
  process.exit(2);
}
const sha256 = (data) => createHash("sha256").update(data).digest("hex");
const readJson = (path) => JSON.parse(readFileSync(path, "utf8"));
const fail = (message) => {
  console.error(`pin-facade-wasm: ${message}`);
  process.exit(1);
};

const manifestPath = join(root, "assets/facade/manifest.json");
const manifest = readJson(manifestPath);
const build = readJson(join(packet, "build-result.json"));
const bindgen = readJson(join(packet, "bindgen-result.json"));
const revision = manifest.source.revision;
if (build.head !== revision || bindgen.head !== revision)
  fail(`packet heads ${build.head}/${bindgen.head} differ from the pinned source ${revision}`);
if (build.exit !== 0 || bindgen.exit !== 0) fail("the packet build or bindgen step did not exit 0");
if ("source_stable" in build && build.source_stable !== true)
  fail("the packet build reports a source change during the build");
if (!bindgen.command.includes("web")) fail("the glue is not wasm-bindgen --target web output");
if (!/0\.2\.130/.test(bindgen.command[0]))
  fail("the glue was not generated by wasm-bindgen 0.2.130");

// Every recorded packet file, by its name inside the packet.
const recorded = new Map(bindgen.files.map((file) => [basename(file.path), file]));
const packetFile = (name) => {
  const file = recorded.get(name);
  if (!file) fail(`bindgen-result.json records no ${name}`);
  const path = join(packet, name === "plurimath_facade.wasm" ? "" : "web", name);
  const bytes = readFileSync(path);
  if (sha256(bytes) !== file.sha256 || bytes.length !== file.bytes)
    fail(`${path} differs from its recorded digest`);
  return { path, bytes, sha256: file.sha256 };
};
const blob = packetFile("facade_bg.wasm");
const glue = packetFile("facade.js");
const glueTypes = packetFile("facade.d.ts");

// The module must match the ABI and the glue host imports the loader admits.
const module = new WebAssembly.Module(blob.bytes);
const exported = new Set(WebAssembly.Module.exports(module).map((entry) => entry.name));
for (const name of [
  "memory",
  "__wbindgen_start",
  "plurimath_facade_abi_version",
  "plurimath_facade_alloc",
  "plurimath_facade_dealloc",
  "plurimath_facade_json",
  "plurimath_facade_free",
])
  if (!exported.has(name)) fail(`the module does not export ${name}`);
const loader = readFileSync(join(root, "src/facade/wasm.ts"), "utf8");
const admitted = new Set(
  [
    ...(loader.match(/const GLUE_IMPORTS = new Set\(\[([^\]]*)\]/)?.[1] ?? "").matchAll(
      /"([^"]+)"/g,
    ),
  ].map((match) => match[1]),
);
const imports = WebAssembly.Module.imports(module);
const unexpected = imports.filter(
  (entry) => entry.module !== "./facade_bg.js" || !admitted.has(entry.name),
);
if (unexpected.length || imports.length !== admitted.size)
  fail(
    `module host imports ${JSON.stringify(imports.map((entry) => entry.name))} differ from GLUE_IMPORTS in src/facade/wasm.ts; update the loader first`,
  );

copyFileSync(blob.path, join(root, "assets/facade", manifest.file));
copyFileSync(glue.path, join(root, manifest.glue.file));
copyFileSync(glueTypes.path, join(root, manifest.glue.types_file));

// The build record keeps the cargo flags; local paths are reduced to names.
const flags = build.command
  .slice(build.command.indexOf("build"))
  .map((arg) => (arg.startsWith("/") ? basename(arg) : arg));
manifest.status = "pinned";
manifest.sha256 = blob.sha256;
manifest.bytes = blob.bytes.length;
manifest.glue.sha256 = glue.sha256;
manifest.glue.types_sha256 = glueTypes.sha256;
manifest.source.build = {
  cargo: flags,
  ...(build.stack_bytes ? { stack_bytes: build.stack_bytes } : {}),
  raw_wasm_sha256: recorded.get("plurimath_facade.wasm")?.sha256 ?? null,
  wasm_bindgen_sha256: bindgen.tool_sha256,
};
writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const asset = `/**
 * The facade WASM pin. Generated by \`scripts/pin-facade-wasm.mjs\` from
 * \`assets/facade/manifest.json\`; do not edit by hand.
 *
 * \`status: "pending"\` means this checkout does not ship the facade binary
 * yet: \`initFacadeWasm\` then needs an explicit \`options.sha256\`.
 */
export const FACADE_WASM_ASSET = Object.freeze({
  status: "pinned" as "pending" | "pinned",
  file: ${JSON.stringify(manifest.file)},
  specifier: "@plurimath/plurimath-ts/facade/plurimath_facade.wasm",
  sha256: ${JSON.stringify(manifest.sha256)} as string | null,
  bytes: ${manifest.bytes} as number | null,
  abi: 1,
  maxRequestBytes: ${manifest.max_request_bytes},
  source: Object.freeze({
    repository: ${JSON.stringify(manifest.source.repository)},
    crate: ${JSON.stringify(manifest.source.crate)},
    revision: ${JSON.stringify(manifest.source.revision)},
  }),
  glue: Object.freeze({
    file: "facade.js",
    sha256: ${JSON.stringify(manifest.glue.sha256)},
    wasmBindgen: "0.2.130",
  }),
});
`;
writeFileSync(join(root, "src/facade/asset.ts"), asset);

const pkgPath = join(root, "package.json");
const pkg = readJson(pkgPath);
if (!pkg.exports["./facade/plurimath_facade.wasm"]) {
  const exports = {};
  for (const [key, value] of Object.entries(pkg.exports)) {
    exports[key] = value;
    if (key === "./facade/wasm")
      exports["./facade/plurimath_facade.wasm"] = "./dist/plurimath_facade.wasm";
  }
  if (!exports["./facade/plurimath_facade.wasm"]) fail("package.json has no ./facade/wasm export");
  pkg.exports = exports;
  writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`);
}
if (!existsSync(join(root, "assets/facade", manifest.file))) fail("the binary was not written");
console.log(
  JSON.stringify({
    pinned: manifest.file,
    sha256: manifest.sha256,
    bytes: manifest.bytes,
    glue: manifest.glue.sha256,
  }),
);
