/** biome-ignore-all lint/style/useNamingConvention: manifest keys are the snake_case pin schema. */
/**
 * Guards for the facade pin and the frozen facade corpus. These run without
 * the binary; the packed runtime replay (scripts/check-facade-packed.mjs)
 * executes the corpus through the installed package.
 */
import { createHash } from "node:crypto";
import { cpSync, mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import { FACADE_COUNTS, loadFacadeCorpus } from "../../scripts/facade-corpus.mjs";
import { FACADE_WASM_ASSET, FacadeWasmError, initFacadeWasm } from "../../src/facade/wasm";

const root = join(import.meta.dirname, "../..");
const sha256 = (bytes: Buffer) => createHash("sha256").update(bytes).digest("hex");
const manifest = JSON.parse(readFileSync(join(root, "assets/facade/manifest.json"), "utf8"));

describe("facade corpus", () => {
  const corpus = loadFacadeCorpus(root);

  it("expands the strict 3798 writer and 1349 parser source cases", () => {
    expect(corpus.counts).toEqual({ writer: FACADE_COUNTS.writer, parser: FACADE_COUNTS.parser });
    const parserRefusals = corpus.cases.filter(
      (c: { kind: string; expected: object }) =>
        c.kind === "parser" && "source_class" in c.expected,
    );
    expect(parserRefusals).toHaveLength(FACADE_COUNTS.parserRefusals);
  });

  it("applies exactly the one guarded Ruby 0a1df68 correction", () => {
    expect(corpus.correction).toBe("intent-table-09/mathml");
  });

  it("keeps the 87 residual text shapes and their Ruby outcomes", () => {
    const outcomes: Record<string, number> = {};
    for (const row of corpus.text87) outcomes[row.outcome] = (outcomes[row.outcome] ?? 0) + 1;
    expect(outcomes).toEqual(FACADE_COUNTS.text87);
  });

  it("keeps unique case identities", () => {
    const keys = corpus.cases.map(
      (c: { kind: string; format: string; id: string }) => `${c.kind}:${c.format}:${c.id}`,
    );
    expect(new Set(keys).size).toBe(keys.length);
  });

  it("refuses a changed fixture byte", () => {
    const copy = mkdtempSync(join(tmpdir(), "facade-fixture-guard-"));
    cpSync(join(root, "test/fixtures/facade"), join(copy, "test/fixtures/facade"), {
      recursive: true,
    });
    const file = join(copy, "test/fixtures/facade/text-closure-followup-87/residual-shapes.json");
    writeFileSync(file, readFileSync(file, "utf8").replace('"model"', '"modeL"'));
    expect(() => loadFacadeCorpus(copy)).toThrow(/differs from provenance/);
  });
});

describe("facade pin", () => {
  const source = readFileSync(join(root, "src/facade/asset.ts"), "utf8");

  it("FACADE_WASM_ASSET is generated from the manifest", () => {
    expect(FACADE_WASM_ASSET.status).toBe(manifest.status);
    expect(FACADE_WASM_ASSET.sha256).toBe(manifest.sha256);
    expect(FACADE_WASM_ASSET.bytes).toBe(manifest.bytes);
    expect(FACADE_WASM_ASSET.maxRequestBytes).toBe(manifest.max_request_bytes);
    expect(FACADE_WASM_ASSET.source.revision).toBe(manifest.source.revision);
    expect(FACADE_WASM_ASSET.glue.sha256).toBe(manifest.glue.sha256);
    expect(source).toContain("Generated by `scripts/pin-facade-wasm.mjs`");
  });

  it("the glue, notices, dependency notices and Cargo.lock match the manifest", () => {
    const pinned: [string, string][] = [
      [manifest.glue.file, manifest.glue.sha256],
      [manifest.glue.types_file, manifest.glue.types_sha256],
      [`assets/facade/${manifest.source.cargo_lock.file}`, manifest.source.cargo_lock.sha256],
      [`assets/facade/${manifest.dependency_notices.manifest}`, manifest.dependency_notices.sha256],
      ...manifest.notices.map((n: { file: string; sha256: string }): [string, string] => [
        `assets/facade/${n.file}`,
        n.sha256,
      ]),
    ];
    const groups = JSON.parse(
      readFileSync(join(root, "assets/facade", manifest.dependency_notices.manifest), "utf8"),
    );
    expect(groups).toHaveLength(manifest.dependency_notices.groups);
    for (const group of groups) {
      if (group.notices.length === 0)
        expect(Object.keys(manifest.dependency_notices.without_notice_files)).toContain(
          group.package,
        );
      for (const notice of group.notices)
        pinned.push([`assets/facade/${notice.file}`, notice.sha256]);
    }
    for (const [file, digest] of pinned)
      expect([file, sha256(readFileSync(join(root, file)))]).toEqual([file, digest]);
  });

  it("a pinned binary matches its manifest; a pending pin names none", () => {
    if (manifest.status === "pinned") {
      const bytes = readFileSync(join(root, "assets/facade", manifest.file));
      expect([sha256(bytes), bytes.length]).toEqual([manifest.sha256, manifest.bytes]);
    } else {
      expect(manifest.status).toBe("pending");
      expect([manifest.sha256, manifest.bytes]).toEqual([null, null]);
    }
  });

  it("refuses to load without a pinned or explicitly named digest", async () => {
    if (manifest.status === "pinned") {
      await expect(initFacadeWasm(new Uint8Array([0, 97, 115, 109]))).rejects.toMatchObject({
        code: "AssetDigestMismatch",
      });
    } else {
      await expect(initFacadeWasm(new Uint8Array([0, 97, 115, 109]))).rejects.toBeInstanceOf(
        FacadeWasmError,
      );
    }
    await expect(
      initFacadeWasm(new Uint8Array([0]), { sha256: "not-a-digest" }),
    ).rejects.toMatchObject({ code: "InvalidAssetSource" });
  });
});
